/// <summary>
/// Represents MIDI message types and their status byte values.
/// </summary>
public enum MIDIMessageType
{
    /// <summary>Note Off message (0x80).</summary>
    NoteOff = 0x80,
    /// <summary>Note On message (0x90).</summary>
    NoteOn = 0x90,
    /// <summary>Polyphonic Aftertouch (0xA0).</summary>
    PolyPressure = 0xA0,
    /// <summary>Control Change (0xB0).</summary>
    ControlChange = 0xB0,
    /// <summary>Program Change (0xC0).</summary>
    ProgramChange = 0xC0,
    /// <summary>Channel Aftertouch (0xD0).</summary>
    ChannelPressure = 0xD0,
    /// <summary>Pitch Bend (0xE0).</summary>
    PitchBend = 0xE0,
    /// <summary>System Exclusive message (0xF0).</summary>
    SystemExclusive = 0xF0,
    /// <summary>MIDI Time Code Quarter Frame (0xF1).</summary>
    TimeCode = 0xF1,
    /// <summary>Song Position Pointer (0xF2).</summary>
    SongPosition = 0xF2,
    /// <summary>Song Select (0xF3).</summary>
    SongSelect = 0xF3,
    /// <summary>Tune Request (0xF6).</summary>
    TuneRequest = 0xF6,
    /// <summary>System Reset (0xFF).</summary>
    SystemReset = 0xFF
}

